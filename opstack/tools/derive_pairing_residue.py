#!/usr/bin/env python3
"""Print the checked BN254 host exponents for the positive pairing witness."""

from math import gcd

P = 21888242871839275222246405745257275088696311157297823662689037894645226208583
R = 21888242871839275222246405745257275088548364400416034343698204186575808495617
X = 4965661367192848881


def main():
    group = P**12 - 1
    kernel, rem = divmod(group, R)
    assert rem == 0
    remaining, rem = divmod(kernel, 27)
    assert rem == 0 and gcd(remaining, 27) == 1
    exponent = P**3 - P**2 + P + 6 * X + 2
    assert exponent % R == 0 and gcd(remaining, exponent) == 1
    assert gcd(P**6 - 1, R) == 1 and (P**6 - 1) % 27 == 0
    print("//! Generated by opstack/tools/derive_pairing_residue.py. Host only.")
    for name, value in (
        ("REMOVE_27_PART", (-remaining * pow(remaining, -1, 27)) % kernel),
        ("NEGATIVE_LAMBDA_ROOT", (-pow(exponent, -1, remaining)) % remaining),
    ):
        limbs = [
            (value >> offset) & ((1 << 64) - 1)
            for offset in range(0, value.bit_length(), 64)
        ]
        print(f"pub(super) const {name}: [u64; {len(limbs)}] = [")
        for limb in limbs:
            print(f"    0x{limb:016x},")
        print("];")


if __name__ == "__main__":
    main()
