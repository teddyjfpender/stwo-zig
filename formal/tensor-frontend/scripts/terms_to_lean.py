#!/usr/bin/env python3
"""Convert a security.zig term dump (TENSOR_TERMS=<tsv>) into a Lean data
module of exact dyadic upper bounds, plus kernel-checked theorems that the
union of the terms is at most 2^-K for the integer K given.

Usage: terms_to_lean.py <terms.tsv> <LeanName> <K_with> <K_without> > TensorFrontend/Data/<LeanName>.lean

Each term (log2_err l, pow w, count c) becomes mant = ceil(c * 2^(S + l - w) * (1 + 2^-40)),
an upper bound of c * 2^(l - w) * 2^S. The 2^-40 relative margin covers the
f64 rounding of 2**x here and of log2 in security.zig (both ~2^-52 relative);
the per-term values themselves are computed by security.zig and are trusted
input to the Lean check, not proved.
"""
import math
import sys
from fractions import Fraction

S = 200
MARGIN = Fraction(1) + Fraction(1, 2**40)


def mant(log2_err: float, pow_bits: int, count: float) -> int:
    x = S + log2_err - pow_bits
    v = Fraction(count) * Fraction(2.0 ** (x - math.floor(x))) * Fraction(2) ** math.floor(x) * MARGIN
    return math.ceil(v)


def lean_str(s: str) -> str:
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main() -> None:
    path, name, k_with, k_without = sys.argv[1], sys.argv[2], int(sys.argv[3]), int(sys.argv[4])
    rows = []
    with open(path) as f:
        for line in f:
            line = line.rstrip('\n')
            if not line:
                continue
            nm, l2, pw, cnt = line.split('\t')
            l2, pw, cnt = float(l2), int(pw), float(cnt)
            rows.append((nm, mant(l2, pw, cnt), mant(l2, 0, cnt)))
    lc = name[0].lower() + name[1:]
    out = []
    out.append(f"-- Generated by scripts/terms_to_lean.py from {path.split('/')[-1]}; do not edit.")
    out.append("import TensorFrontend.Security")
    out.append("")
    out.append("namespace TensorFrontend.Data")
    out.append("open TensorFrontend.Security")
    out.append("")
    out.append(f"/-- (name, mantissa with work, mantissa without work), each an upper bound of the term times 2^{S}. -/")
    out.append(f"def {lc}Terms : List (String × Nat × Nat) := [")
    out.append(",\n".join(f"  ({lean_str(n)}, {a}, {b})" for n, a, b in rows))
    out.append("]")
    out.append("")
    out.append(f"def {lc}With : List Nat := [{', '.join(str(a) for _, a, _ in rows)}]")
    out.append(f"def {lc}Without : List Nat := [{', '.join(str(b) for _, _, b in rows)}]")
    out.append("")
    out.append(f"/-- Kernel-checked: the summed terms (with proof of work) are <= 2^-{k_with}. -/")
    out.append(f"theorem {lc}_with_bits : dyadicOK {lc}With {S} {k_with} = true := by decide")
    out.append(f"/-- Kernel-checked: the summed terms (without proof of work) are <= 2^-{k_without}. -/")
    out.append(f"theorem {lc}_without_bits : dyadicOK {lc}Without {S} {k_without} = true := by decide")
    out.append("")
    out.append("end TensorFrontend.Data")
    print("\n".join(out))


if __name__ == '__main__':
    main()
