#!/usr/bin/env python3
"""Generate native service-column offsets from the canonical Zig layouts."""
import argparse, hashlib, pathlib, re
ROOT=pathlib.Path(__file__).resolve().parents[1]
SOURCES={"bulk_layout":"src/frontends/riscv/rv64/air/delegations/bulk_memory/layout.zig","sponge_layout":"src/frontends/riscv/rv64/air/delegations/keccak_sponge/layout.zig"}
OUT=ROOT/'src/backends/cuda/native/rv64/service_witness_layouts.h'
def generate():
 out=['// Generated by scripts/rv64_service_witness_layouts.py; do not edit.','#pragma once','#include <stdint.h>','namespace stwo::cuda::rv64 {']
 for namespace,path in SOURCES.items():
  text=(ROOT/path).read_text();out+=['// '+path+' sha256='+hashlib.sha256(text.encode()).hexdigest(),'namespace '+namespace+' {']
  for match in re.finditer(r'pub const (\w+) = struct \{(.*?)\n\};',text,re.S):
   out+=['namespace '+match[1]+' {']
   for name,value in re.findall(r'pub const (\w+) = (\d+);',match[2]):out+=['constexpr uint32_t '+('new_' if name=='new' else name)+' = '+value+';']
   out+=['}']
  out+=['}']
 out+=['}'];return '\n'.join(out)+'\n'
if __name__=='__main__':
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');a=p.parse_args();expected=generate()
 if a.check:
  if not OUT.exists() or OUT.read_text()!=expected:raise SystemExit('service witness offsets are stale; regenerate')
 else:OUT.write_text(expected)
