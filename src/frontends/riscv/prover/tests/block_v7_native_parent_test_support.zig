const std = @import("std");
const core = @import("stwo_core");
const Cpu = @import("stwo_cpu_backend").CpuBackend;
const Profile = @import("../../recursion/block_v7_native_fixed_profile_v1.zig");
const Native = @import("../block_v7_native_proof_v1.zig");
pub fn qualify(a: std.mem.Allocator, profile: *const Profile.Owned, capture: *const Native.VerifiedCapture) !void {
    const Cold = @import("../../recursion/block_v7_native_fixed_roster_v1.zig");
    const Prepare = @import("../../recursion/block_v7_native_preparation_v1.zig");
    const Public = @import("../../recursion/block_v7_native_public_v1.zig");
    const Protocol = @import("../../recursion/block_v7_native_parent_protocol_v1.zig");
    const Parent = @import("../../recursion/blake3_execution_parent_proof.zig");
    const Receive = @import("../../recursion/block_v7_native_receiver_v1.zig");
    const parent_profile = @import("../../recursion/blake3_execution_parent_protocol.zig").Profile.diagnostic_q8_pow0;
    const claims = Public.Claims{ .projection = capture.claims, .access = capture.memory_claims };
    var cold = try Cold.Owned.derive(a, profile, claims, 2, .{});
    defer cold.deinit();
    const expected_base = try Parent.ForBackend(Cpu).deriveKeyFromFixed(a, cold.fixed, cold.context, parent_profile);
    const roster = [_]Protocol.Bus.Expected{Cold.expected(profile)};
    const key = try Protocol.Key.fromGeometry(expected_base, cold.wires, &roster);
    var ready = try Prepare.prepare(a, profile, capture, 2, .{});
    var ready_live = true;
    defer if (ready_live) ready.deinit();
    try cold.validateLive(&ready);
    const live_base = try Parent.ForBackend(Cpu).deriveKeyWithProfile(a, &ready.recursive, parent_profile);
    try std.testing.expectEqualDeep(expected_base, live_base);
    const admission = try Protocol.Admission.init(key, try key.identity(), ready.wires, .{ .children = &.{ready.values} }, &roster);
    const Plan = @import("../../recursion/blake3_native_parent_producer.zig").PlanForProtocol(Cpu, Protocol);
    const plan = try Plan.init(a, &ready.recursive.rows, admission);
    var plan_live = true;
    defer if (plan_live) plan.deinit();
    var proof = try plan.prove(a, &ready.recursive.rows);
    var proof_live = true;
    defer if (proof_live) proof.deinit();
    const bytes = try Parent.codec.encode(a, &proof, &admission);
    defer a.free(bytes);
    proof.deinit();
    proof_live = false;
    plan.deinit();
    plan_live = false;
    ready.deinit();
    ready_live = false;
    var verified = try Receive.verify(a, bytes, profile, claims, key, cold.wires);
    defer verified.deinit();
    try std.testing.expectEqualDeep(capture.open, verified.open);
    const changed_claims = try a.dupe(@TypeOf(capture.claims[0]), capture.claims);
    defer a.free(changed_claims);
    changed_claims[0].sum = changed_claims[0].sum.add(core.fields.qm31.QM31.one());
    changed_claims[1].sum = changed_claims[1].sum.sub(core.fields.qm31.QM31.one());
    try std.testing.expectError(error.InvalidProviderBatchPublicClosure, Receive.verify(a, bytes, profile, .{ .projection = changed_claims, .access = claims.access }, key, cold.wires));
    var canonical = try Public.reconstruct(a, profile, claims);
    defer canonical.deinit();
    var changed = try canonical.clone(a);
    defer changed.deinit();
    changed.statement.roots_offset[0] += 1;
    try std.testing.expectError(error.UntrustedNativePublicFrame, Public.requireSameFrame(changed, canonical));
    var bad_key = key;
    bad_key.preprocessed_root[0] ^= 1;
    if (Receive.verify(a, bytes, profile, claims, bad_key, cold.wires)) |ok| {
        var unexpected = ok;
        unexpected.deinit();
        return error.AcceptedWrongNativeParentKey;
    } else |_| {}
    std.debug.print("V7_NATIVE_PARENT commitments={d} cold_live_key=true cold_live_rows=true detached_verify=true open_sources_only=true proof_bytes={d} producer_rows=0\n", .{ profile.trace_count + 1, bytes.len });
}
