//! Genuine original local-source STARK: native direct AIR and all projections,
//! ordered endpoint AIR, and all thirteen range requests per endpoint.
//! Global WORD/ROM/byte/table providers remain explicitly OPEN.
const std = @import("std");
const core = @import("stwo_core");
const engine = @import("stwo_prover_engine");
const Cpu = @import("stwo_cpu_backend").CpuBackend;
const S = core.proof_suites.Blake3;
const Q = core.fields.qm31.QM31;
const Components = @import("../block_v8_native_endpoint_components_v1.zig");
const Local = @import("../block_v8_native_endpoint_local_source_v1.zig");
const Endpoint = @import("../block_v8_ram_endpoint_component_v1.zig");
const Range = @import("../block_v8_endpoint_range_provider_v1.zig");
const T = @import("../block_v7_memory_trace_v1.zig");
const Descriptor = @import("../block_v8_endpoint_source_descriptor_v1.zig");
const Closure = @import("../block_v8_native_endpoint_closure_v1.zig");
const K = @import("../block_v8_ram_endpoint_kernel_v1.zig");
const E = @import("../block_v7_execution_epoch_v1.zig");
const Shape = @import("../../air/statement.zig").Blake3ExecutionStatement;
const Scheme = engine.pcs.CommitmentSchemeProver(Cpu, S.Hasher, S.MerkleChannel);
fn verifyFresh(a: std.mem.Allocator, proof: *const S.Proof, shape: *const Shape, scope: Closure.Scope, claims: []const Components.Claim, endpoint_sums: [Endpoint.PLANES]Q, range_sums: [Range.Spec.PLANES]Q, drawn: *const E.Drawn, config: core.pcs.PcsConfig, first_roots: [4][32]u8) !void {
    const owner = try Local.Owner.init(a, shape, scope, claims, endpoint_sums, range_sums, drawn);
    defer owner.deinit();
    var joined = try owner.verifying();
    defer joined.deinit(a);
    const roots = proof.commitment_scheme_proof.commitments.items;
    if (roots.len != 8 or !std.meta.eql(roots[0..4].*, first_roots) or !std.meta.eql(config, proof.commitment_scheme_proof.config)) return error.UntrustedOpenEndpointLocalProof;
    var fixed_columns = try Local.fixedColumns(a, shape, scope.endpoint_count);
    defer fixed_columns.deinit();
    const fixed_logs = try a.alloc(u32, fixed_columns.columns.len);
    defer a.free(fixed_logs);
    for (fixed_columns.columns, fixed_logs) |column, *log| log.* = column.log_size;
    var fixed = try Scheme.init(a, config);
    defer fixed.deinit(a);
    var ignored = S.Channel{};
    try fixed.commitBorrowedStreaming(a, fixed_columns.columns, 8, &ignored);
    if (!std.meta.eql(fixed.trees.items[0].root(), roots[0])) return error.UntrustedOpenEndpointLocalFixedRoot;
    var channel = drawn.channel;
    try Local.recordClaims(&channel, owner.native.layout.digest, claims, endpoint_sums, range_sums);
    var verifier = try core.pcs.verifier.CommitmentSchemeVerifier(S.Hasher, S.MerkleChannel).init(a, config);
    defer verifier.deinit(a);
    try verifier.commit(a, roots[0], fixed_logs, &ignored);
    try verifier.commit(a, roots[1], owner.native.main, &ignored);
    try verifier.commit(a, roots[2], &owner.endpoint_main_logs, &ignored);
    try verifier.commit(a, roots[3], &owner.range_main_logs, &ignored);
    try verifier.commit(a, roots[4], owner.native.interactions, &channel);
    try verifier.commit(a, roots[5], &owner.endpoint_interaction_logs, &channel);
    try verifier.commit(a, roots[6], &owner.range_interaction_logs, &channel);
    var capture: core.verifier.ProofCapture(S.Hasher) = undefined;
    try core.verifier.verifyBorrowedWithProofCapture(S.Hasher, S.MerkleChannel, a, joined.handles, &channel, &verifier, proof, &capture);
    defer capture.deinit(a);
    // Closure follows proof authentication; none of the open global/ROM/table
    // claims are accepted as an execution theorem by this local test.
    _ = try Local.close(a, shape, owner, claims, drawn);
}
test "v8 endpoint local native endpoint and range AIR prove one source without WORD sidecars" {
    const a = std.testing.allocator;
    const code = [_]u32{ 0x00700313, 0x00900393, 0x02730433, 0x001002b7, 0x10028293, 0x0082a023, 0x0002a483, 0x0000006f };
    const elf = @import("../../runner/guest_precompile/test_elf.zig").buildReleaseProgram(code.len, &code, 512, .rv32im_zkvm_v1);
    var session = try @import("../../runner/mod.zig").BaseExecutionSession.init(a, &elf, .{ .trace_retention = .segment_owned, .clock_frame = .leaf_local });
    defer session.deinit();
    var segment = try session.startSegment(code.len - 1);
    defer segment.deinit();
    try std.testing.expectEqual(@as(u32, 63), segment.exit_cpu.regs[9]);
    var io = try @import("../blake3_segment_public.zig").Owned.init(a, &segment);
    defer io.deinit();
    io.data.program_root = .{ .bytes = @splat(7) };
    io.data.initial_rw_root = null;
    io.data.final_rw_root = null;
    io.data.io_entries.input_len = 0;
    io.data.io_entries.input_words = &.{};
    io.data.io_entries.output_len = 0;
    io.data.io_entries.output_words = &.{};
    const native = try @import("../blake3_execution_trace.zig").Owner.initWithExternal(a, &segment.execution_trace, io.data, &segment.state_chain_tracker, 0);
    var native_live = true;
    defer if (native_live) native.deinit();
    try native.sealNativeOnly();
    const shape = native.statement;
    const config = @import("../../recursion/blake3_execution_parent_protocol.zig").Profile.diagnostic_q8_pow0.config();
    var scheme = try Scheme.init(a, config);
    var scheme_live = true;
    defer if (scheme_live) scheme.deinit(a);
    const endpoint_policy = K.Policy{ .source_ordinal = 0, .max_local_clock = try Closure.maxLocalClock(shape.public_data.clock) };
    var last_memory_clock: u32 = 0;
    for (segment.state_chain_tracker.accesses.items) |access| {
        if (access.addr_space == 1) last_memory_clock = @max(last_memory_clock, access.clk);
    }
    try std.testing.expectEqual(@as(u32, 27), last_memory_clock);
    const endpoint = try K.constructWithPrevious(.{ .address = 0x100100, .initial = 0, .final = 63, .last_clock = last_memory_clock }, null, endpoint_policy);
    var matrix = try T.Matrix.init(a, 4, Endpoint.Spec.FIXED_COUNT + Endpoint.Spec.MAIN_COUNT, 1 << 20);
    var matrix_live = true;
    defer if (matrix_live) matrix.deinit();
    matrix.set(0, 0, core.fields.m31.M31.one());
    matrix.set(1, 0, core.fields.m31.M31.one());
    for (endpoint, 0..) |value, column| matrix.set(2 + column, 0, try value.tryIntoM31());
    var range = try Range.Owned.init(a, matrix, 1, .{});
    var range_live = true;
    defer if (range_live) range.deinit();
    // Direct carry Booleanity alone is insufficient. The thirteenth range
    // request rejects this forged signed low limb before witness admission.
    matrix.set(2 + 21, 0, core.fields.m31.M31.one());
    try std.testing.expectError(error.InvalidEndpointRange16, Range.Owned.init(a, matrix, 1, .{}));
    matrix.set(2 + 21, 0, core.fields.m31.M31.zero());
    var fixed_columns = try Local.fixedColumns(a, &shape, 1);
    defer fixed_columns.deinit();
    for (native.preprocessed.items, fixed_columns.columns[0..native.preprocessed.items.len]) |producer, independent| try std.testing.expectEqualSlices(core.fields.m31.M31, producer.values, independent.values);
    var first_channel = S.Channel{};
    first_channel.mixU32s(&.{ 0x42384c54, 1 });
    try scheme.commitBorrowedStreaming(a, fixed_columns.columns, 8, &first_channel);
    try scheme.commitBorrowedStreaming(a, native.main.items, 8, &first_channel);
    try scheme.commitBorrowedStreaming(a, matrix.columns[Endpoint.Spec.FIXED_COUNT..], 8, &first_channel);
    try scheme.commitBorrowedStreaming(a, range.range16.columns[Range.Spec.FIXED_COUNT..], 8, &first_channel);
    var roots = try scheme.roots(a);
    defer roots.deinit(a);
    const first_roots = roots.items[0..4].*;
    const descriptor = try Descriptor.Descriptor.derive(a, &shape, .rv32im_zkvm_v1, .{ .clock_frame = .leaf_local, .global_first_cycle = 1, .cycle_count = shape.public_data.clock }, endpoint_policy, 1, first_roots);
    const entries = [_]E.Entry{try descriptor.entry()};
    var counts: E.Counts = @splat(0);
    counts[@intFromEnum(E.Family.native)] = 1;
    const epoch = try E.Epoch.init(@splat(19), config, counts, &entries, 1);
    const drawn = try epoch.draw(a);
    var interaction = try Components.Interactions.generate(a, &shape, native.main.items, &drawn);
    var interaction_live = true;
    defer if (interaction_live) interaction.deinit();
    const claims = try a.dupe(Components.Claim, interaction.claims);
    defer a.free(claims);
    var endpoint_interaction = try Local.endpointInteractions(a, matrix, descriptor.scope, &drawn, 1 << 20);
    var endpoint_interaction_live = true;
    defer if (endpoint_interaction_live) endpoint_interaction.deinit();
    var range_interaction = try range.interactions(a, drawn.memory, 8 << 20);
    var range_interaction_live = true;
    defer if (range_interaction_live) range_interaction.deinit();
    const endpoint_sums = endpoint_interaction.sums;
    const range_sums = range_interaction.sums;
    const owner = try Local.Owner.init(a, &shape, descriptor.scope, claims, endpoint_sums, range_sums, &drawn);
    var owner_live = true;
    defer if (owner_live) owner.deinit();
    var joined = try owner.proving();
    var joined_live = true;
    defer if (joined_live) joined.deinit(a);
    _ = try Local.close(a, &shape, owner, claims, &drawn);
    var channel = drawn.channel;
    try Local.recordClaims(&channel, owner.native.layout.digest, claims, endpoint_sums, range_sums);
    try scheme.commitBorrowedStreaming(a, interaction.columns, 8, &channel);
    try scheme.commitBorrowedStreaming(a, endpoint_interaction.matrix.columns, 8, &channel);
    try scheme.commitBorrowedStreaming(a, range_interaction.matrix.columns, 8, &channel);
    scheme_live = false;
    var proof = try engine.prove.prove(Cpu, S.Hasher, S.MerkleChannel, a, joined.handles, &channel, scheme);
    defer proof.deinit(a);
    // Fresh verification owns no producer columns, projections or key objects.
    joined.deinit(a);
    joined_live = false;
    owner.deinit();
    owner_live = false;
    interaction.deinit();
    interaction_live = false;
    native.deinit();
    native_live = false;
    matrix.deinit();
    matrix_live = false;
    range.deinit();
    range_live = false;
    endpoint_interaction.deinit();
    endpoint_interaction_live = false;
    range_interaction.deinit();
    range_interaction_live = false;
    try verifyFresh(a, &proof, &shape, descriptor.scope, claims, endpoint_sums, range_sums, &drawn, config, first_roots);
    var forged_endpoint = endpoint_sums;
    forged_endpoint[2] = forged_endpoint[2].add(Q.one());
    forged_endpoint[3] = forged_endpoint[3].sub(Q.one());
    try Range.closeRangeClaims(1, forged_endpoint, range_sums);
    if (verifyFresh(a, &proof, &shape, descriptor.scope, claims, forged_endpoint, range_sums, &drawn, config, first_roots)) |_| return error.AcceptedEndpointPhysicalClaimForgery else |err| if (err == error.OutOfMemory) return err;
    try std.testing.expect(claims.len > 1);
    const before = claims[0].sum.add(claims[1].sum);
    claims[0].sum = claims[0].sum.add(Q.one());
    claims[1].sum = claims[1].sum.sub(Q.one());
    try std.testing.expect(before.eql(claims[0].sum.add(claims[1].sum)));
    if (verifyFresh(a, &proof, &shape, descriptor.scope, claims, endpoint_sums, range_sums, &drawn, config, first_roots)) |_| return error.AcceptedEndpointNativePhysicalClaimForgery else |err| if (err == error.OutOfMemory) return err;
}
