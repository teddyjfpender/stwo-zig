const std = @import("std");
const S = @import("spec.zig");
const W = @import("witness.zig");
const L = @import("lowering.zig");
const NW = @import("normalized_witness.zig");
const C = @import("fixture.zig");
const V = @import("../bn254_miller/vectors.zig");
const R = @import("../bn254_residue/vectors.zig");
test "pairing fixture source row once and independent frontier authority" {
    var p = try L.Program.init(std.testing.allocator);
    defer p.deinit();
    var source = try W.Witness.init(std.testing.allocator, V.INPUT, .{ .seed = R.POSITIVE.seed, .scale = R.POSITIVE.c[0..6].*, .inverse2 = R.POSITIVE.inverse2 });
    defer source.deinit();
    var values = try NW.Witness.init(std.testing.allocator, &p, &source);
    defer values.deinit();
    const expected = try S.initialValues(V.INPUT);
    var model = try C.Model.init(&p, &values, &expected);
    try std.testing.expectError(error.PairingFixtureMissingColumns, model.requireColumns());
    const first = try model.materialize(.arithmetic, 0);
    try std.testing.expectEqual(@as(u32, 1), first.main_values[0]);
    for (0..C.fixedWidth(.arithmetic)) |col| _ = first.fixed(col);
    const padding = try model.materialize(.arithmetic, 32767);
    for (padding.main_values) |v| try std.testing.expectEqual(0, v);
    for (0..C.fixedWidth(.arithmetic)) |col| try std.testing.expect(padding.fixed(col).isZero());
    const front = try model.materialize(.frontier, 0);
    for (0..32) |i| try std.testing.expect(front.main(1 + i).eql(front.fixed(3 + i)));
    const end = try model.materialize(.frontier, L.FRONTIER_ROWS - 1);
    for (0..32) |i| try std.testing.expect(end.main(1 + i).eql(end.fixed(3 + i)));
    var wrong = expected;
    wrong[24] = (wrong[24] + 1) % S.B.BN254_P;
    try std.testing.expectError(error.PairingLiteralAuthority, C.Model.init(&p, &values, &wrong));
    wrong = expected;
    wrong[0] = S.B.BN254_P;
    try std.testing.expectError(error.NonCanonicalPairingFrontier, C.Model.init(&p, &values, &wrong));
    var table: [256]C.M = @splat(C.M.zero());
    try std.testing.expectError(error.PairingFixtureColumns, model.installColumns(.table, table[0..255]));
    try model.installColumns(.table, &table);
    try std.testing.expectError(error.PairingFixtureDuplicateColumns, model.installColumns(.table, &table));
    try std.testing.expectError(error.PairingFixtureMissingColumns, model.materialize(.table, 0));
    const view = model.view(.table, 17);
    try std.testing.expect(view.main(0).isZero());
}
