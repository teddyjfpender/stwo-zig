//! Pending two-child R7 parent using a retained actual CPU proof unchanged.
//! No full execution, adjacency, manifest closure or root admission is claimed.
const std = @import("std");
const CPU = @import("../pure_p2_cpu_leaf_test.zig");
const P = @import("outer_proof.zig");
const K = @import("outer_authority.zig").Key;
const Source = @import("source_key.zig").SourceKey;
const Fixture = @import("recursive_test.zig");
const Fold = @import("fold.zig");
pub fn run(a: std.mem.Allocator, view: CPU.ShapeView, path: []const u8) !void {
    const actual_path = std.posix.getenv("STWO_OP_R7_CPU_LEAF") orelse return error.MissingR7CpuLeaf;
    const fixture_path = std.posix.getenv("STWO_OP_R7_TINY_LEAF") orelse return error.MissingR7TinyLeaf;
    const bytes = try std.fs.cwd().readFileAlloc(a, actual_path, 16 << 20);
    defer a.free(bytes);
    const tiny_bytes = try std.fs.cwd().readFileAlloc(a, fixture_path, 16 << 20);
    defer a.free(tiny_bytes);
    const actual_output = try view.expectedOutput(a);
    var actual = try Source.initCpu(a, view);
    defer actual.deinit();
    var captured = try P.verifyCaptured(a, &actual.authority, &actual_output, bytes);
    defer captured.deinit(a);
    var tiny_witness = try Fixture.source(a, 7, 3, false);
    defer tiny_witness.deinit();
    const tiny_output = Fixture.outputs(&tiny_witness);
    var tiny_source = try Fixture.source(a, 7, 3, true);
    defer tiny_source.deinit();
    var tiny = try K.init(a, &tiny_source, view.key.profile);
    defer tiny.deinit();
    var tiny_capture = try P.verifyCaptured(a, &tiny, &tiny_output, tiny_bytes);
    defer tiny_capture.deinit(a);
    const pair = Fold.Source{ .children = .{ .{ .key = .{ .r7 = &actual.authority }, .verified = .{ .r7 = &captured }, .output = actual_output }, .{ .key = .{ .r7 = &tiny }, .verified = .{ .r7 = &tiny_capture }, .output = tiny_output } } };
    var parent = try pair.buildForProving(a);
    defer parent.deinit();
    try std.testing.expect(try parent.isCircuitValid());
    const counts = try @import("cpu_source_test.zig").Counts.derive(&parent);
    var key = try K.init(a, &parent, view.key.profile);
    var owns_key = true;
    defer if (owns_key) key.deinit();
    const identity = key.core.base.identity;
    const expected = try pair.expectedOutput();
    var timer = try std.time.Timer.start();
    const proof = try P.prove(a, &parent, &key, &expected);
    defer a.free(proof);
    const prove_ns = timer.lap();
    key.deinit();
    owns_key = false;
    // Fresh source authority depends only on the two admitted source keys.
    var fresh = try (Fold.TraceSource{ .keys = .{ .{ .r7 = &actual.authority }, .{ .r7 = &tiny } } }).build(a);
    defer fresh.deinit();
    var receiver = try K.init(a, &fresh, view.key.profile);
    defer receiver.deinit();
    const fresh_setup_ns = timer.lap();
    try std.testing.expectEqualSlices(u8, &identity, &receiver.core.base.identity);
    try P.verify(a, &receiver, &expected, proof);
    const fresh_verify_ns = timer.lap();
    const swapped = try Fold.digest(tiny_output, actual_output);
    try std.testing.expect(std.meta.isError(P.verify(a, &receiver, &swapped, proof)));
    try std.fs.cwd().makeDir(path);
    var dir = try std.fs.cwd().openDir(path, .{});
    defer dir.close();
    const write = @import("../../rv64_ethereum_batch_receipt.zig").writeExclusive;
    try write(dir, "parent.bin", proof);
    var sha: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(proof, &sha, .{});
    const receipt = try std.json.Stringify.valueAlloc(a, .{ .schema = "op-r7-retained-actual-cpu-plus-tiny-parent-v2", .bytes = proof.len, .sha256 = std.fmt.bytesToHex(sha, .lower), .source_identity = std.fmt.bytesToHex(identity, .lower), .actual_child_source = std.fmt.bytesToHex(actual.authority.core.base.identity, .lower), .tiny_child_source = std.fmt.bytesToHex(tiny.core.base.identity, .lower), .counts = counts, .prove_ns = prove_ns, .fresh_setup_ns = fresh_setup_ns, .fresh_verify_ns = fresh_verify_ns, .actual_cpu_reproved = false, .ordered_sources_and_public_words_bound = true, .swapped_public_frames_rejected = true, .pending_parent_only = true, .execution_root_admitted = false, .heavy_run = false, .controlled_speed_measurement = false }, .{ .whitespace = .indent_2 });
    defer a.free(receipt);
    try write(dir, "receipt.json", receipt);
    std.debug.print("OP_R7_ACTUAL_CPU_PARENT {s}\n", .{receipt});
}
