//! Opt-in actual SMALL CPU outer proof. No R7 recursive/root admission.
const std = @import("std");
const Engine = @import("stwo_prover_engine");
const CPU = @import("../pure_p2_cpu_leaf_test.zig");
const Source = @import("cpu_source.zig");
const Key = @import("outer_authority.zig").Key;
const Proof = @import("outer_proof.zig");
const Counts = @import("cpu_source_test.zig").Counts;
pub fn run(a: std.mem.Allocator, view: CPU.ShapeView, path: []const u8, phases: *CPU.CompleteCounts) !Counts {
    try std.fs.cwd().makeDir(path);
    var dir = try std.fs.cwd().openDir(path, .{});
    defer dir.close();
    const write = @import("../../rv64_ethereum_batch_receipt.zig").writeExclusive;
    const expected = try view.expectedOutput(a);
    var timer = try std.time.Timer.start();
    var identity: [32]u8 = undefined;
    var fixed: @TypeOf(@as(Key, undefined).core.base.fixed_root) = undefined;
    var counts: Counts = undefined;
    var build_ns: u64 = 0;
    var setup_ns: u64 = 0;
    var prove_ns: u64 = 0;
    const proof = blk: {
        var owner = try Source.build(a, view, false, phases);
        defer owner.deinit();
        try std.testing.expect(try owner.isCircuitValid());
        for (owner.base.circuit.output.items[1..], expected) |id, output| try std.testing.expect(owner.base.get(.{ .idx = id }).eql(output));
        counts = try Counts.derive(&owner);
        build_ns = timer.lap();
        var key = try Key.init(a, &owner, view.key.profile);
        defer key.deinit();
        identity = key.core.base.identity;
        fixed = key.core.base.fixed_root;
        setup_ns = timer.lap();
        var recorder = Engine.stage_profile.Recorder.initWithOptions(a, "cpu", "op_r7_actual_small_cpu_leaf", .{ .capture_tasks = false, .capture_process_usage = true });
        defer recorder.deinit();
        const encoded = try Proof.proveProfiled(a, &owner, &key, &expected, &recorder);
        errdefer a.free(encoded);
        prove_ns = timer.lap();
        try write(dir, "leaf.bin", encoded);
        var stages = try recorder.snapshot(a);
        defer stages.deinit(a);
        const json = try std.json.Stringify.valueAlloc(a, stages, .{ .whitespace = .indent_2 });
        defer a.free(json);
        try write(dir, "stages.json", json);
        break :blk encoded;
    };
    defer a.free(proof);
    // Producer witness AND key are dead. Reconstruct source authority independently.
    timer.reset();
    var fresh = try Source.build(a, view, true, null);
    defer fresh.deinit();
    var key = try Key.init(a, &fresh, view.key.profile);
    defer key.deinit();
    const fresh_setup_ns = timer.lap();
    try std.testing.expectEqualSlices(u8, &identity, &key.core.base.identity);
    try std.testing.expectEqualSlices(u8, &fixed, &key.core.base.fixed_root);
    try Proof.verify(a, &key, &expected, proof);
    const fresh_verify_ns = timer.lap();
    var wrong = expected;
    wrong[8] = wrong[8].add(@import("../../rv64_recursion/om31_poseidon/common.zig").Q.one());
    try std.testing.expect(std.meta.isError(Proof.verify(a, &key, &wrong, proof)));
    var sha: [32]u8 = undefined;
    std.crypto.hash.sha2.Sha256.hash(proof, &sha, .{});
    const receipt = try std.json.Stringify.valueAlloc(a, .{ .schema = "op-r7-actual-small-cpu-physical-v2", .protocol = "STP27I02", .bytes = proof.len, .sha256 = std.fmt.bytesToHex(sha, .lower), .source_identity = std.fmt.bytesToHex(identity, .lower), .fixed_root = fixed, .source_build_ns = build_ns, .setup_ns = setup_ns, .prove_ns = prove_ns, .fresh_source_setup_ns = fresh_setup_ns, .fresh_verify_ns = fresh_verify_ns, .counts = counts, .same_public_output = expected, .producer_destroyed_before_fresh_source = true, .wrong_output_rejected = true, .heavy_run = false, .controlled_speed_measurement = false, .production_admission = false, .root_admission = false }, .{ .whitespace = .indent_2 });
    defer a.free(receipt);
    try write(dir, "leaf.json", receipt);
    try std.posix.fsync(dir.fd);
    return counts;
}
