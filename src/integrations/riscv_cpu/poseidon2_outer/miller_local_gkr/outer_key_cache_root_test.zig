test "Miller borrowed verifier source leaves retain shared key ownership and source guards" {
    const a = std.testing.allocator;
    var key = try Native.Key.init(a, .op_target_b4_q72_p0_fold4_v1, 8, 15);
    defer key.deinit();
    var arena = std.heap.ArenaAllocator.init(a);
    defer arena.deinit();
    const scratch = arena.allocator();
    const span = Native.Span{ .calls = 1, .first_id = 7 };
    const shape = try Full.geometry(scratch, &key, span);
    const values = try Skeleton.init(scratch, &shape);
    const instances = try (try key.geometry(span)).instances();
    const lengths = try scratch.alloc(u8, try Template.countFor(&instances));
    @memset(lengths, 4);
    const proof = try Template.skeletonFor(scratch, &instances, lengths);
    const root = P.hashWords(&.{});
    const view = View{ .key = &key, .span = span, .expected = try key.expected(span, 0), .manifest = root, .main = root, .receipt = root, .claims = @splat(@import("stwo_core").fields.om31.OM31.zero()), .local = &proof, .shape = &shape, .values = &values };
    var cache = try Cache.initForVerification(a, 2 << 30, 1);
    defer cache.deinit() catch unreachable;
    var one = try Leaf.initLocalMillerCachedForVerification(a, view, &cache);
    var one_live = true;
    defer if (one_live) one.deinit();
    var other = view;
    other.span.first_id = 17;
    other.expected = try key.expected(other.span, 1);
    var two = try Leaf.initLocalMillerCachedForVerification(a, other, &cache);
    var two_live = true;
    defer if (two_live) two.deinit();
    try std.testing.expect((try one.key()) == (try two.key()));
    var control = try Leaf.initLocalMiller(a, view);
    defer control.deinit();
    try std.testing.expectEqualSlices(u8, &(try control.key()).base.identity, &(try one.key()).base.identity);
    try std.testing.expectEqualSlices(u8, &(try control.key()).base.fixed_root, &(try one.key()).base.fixed_root);
    control.retireProverData();
    try std.testing.expectEqual(@as(usize, 2), cache.snapshot().leases);
    try std.testing.expectEqual(@as(usize, 1), cache.snapshot().hits);
    one.retireProverData(); // must not free shared/borrowed authority.
    const identity = (try two.key()).base.identity;
    one.deinit();
    one_live = false;
    try std.testing.expectEqual(@as(usize, 1), cache.snapshot().leases);
    try std.testing.expectEqualSlices(u8, &identity, &(try two.key()).base.identity);
    var bad = view;
    bad.expected.statement[0] ^= 1;
    try std.testing.expectError(error.MillerLocalExpected, Leaf.initLocalMillerCachedForVerification(a, bad, &cache));
    var cap_values = values;
    cap_values.cap_log = 1;
    bad = view;
    bad.values = &cap_values;
    try std.testing.expectError(error.OpRootLeafCapVariant, Leaf.initLocalMillerCachedForVerification(a, bad, &cache));
    try std.testing.expectEqual(@as(usize, 1), cache.snapshot().leases);
    two.deinit();
    two_live = false;
    try std.testing.expectEqual(@as(usize, 0), cache.snapshot().leases);
    var prover_cache = try Cache.init(a, 4096, 1);
    defer prover_cache.deinit() catch unreachable;
    try std.testing.expectError(error.MillerOuterCacheVerificationOnly, Leaf.initLocalMillerCachedForVerification(a, view, &prover_cache));
}

test "Miller cached root-only source receiver preserves retained root and capacity fallback" {
    const path = std.posix.getenv("STWO_OP_SUITE_ROOT_VERIFY") orelse return error.SkipZigTest;
    const budget = try Engine.host_budget_allocator.SharedHostBudget.create(std.heap.smp_allocator, 12 << 30);
    defer budget.destroy();
    {
        const a = budget.allocator();
        var pool: Engine.work_pool.WorkPool = .{};
        try pool.initInPlaceWithOptions(.{ .worker_count = 8 });
        defer pool.deinit();
        var binding = try Engine.work_pool.ScopedPoolBinding.init(&pool);
        defer binding.deinit();
        var dir = try std.fs.cwd().openDir(path, .{});
        defer dir.close();
        var source_dir = try dir.openDir("source-only", .{});
        defer source_dir.close();
        try std.testing.expectError(error.FileNotFound, source_dir.access("native-op.bin", .{}));
        const json = try source_dir.readFileAlloc(a, "fixture-source.json", 1 << 20);
        defer a.free(json);
        const header = try std.json.parseFromSlice(Header, a, json, .{});
        defer header.deinit();
        try header.value.suite.requireExpected(Source.SUITE);
        const cells = try @import("../../word16_execution/cells_wire.zig").read(a, source_dir, 80);
        defer cells.deinit(a);
        var source = try Source.Owner.init(a, header.value.metadata, cells.initial, cells.terminal);
        defer source.deinit();
        const root = try dir.readFileAlloc(a, "root.bin", 2 << 20);
        defer a.free(root);
        const sidecar = try dir.readFileAlloc(a, "root-sidecar.bin", 64 << 20);
        defer a.free(sidecar);
        const shapes = try dir.readFileAlloc(a, "root-gkr-shapes.bin", @import("../pure_p2_gkr_templates_wire.zig").MAX_BYTES);
        defer a.free(shapes);
        const cached = try Receiver.verifyFixtureSourceWithLimits(a, source.view(), root, sidecar, shapes, true, .{ .miller_cache_bytes = 1 << 30 });
        try std.testing.expectEqual(@as(usize, 2), cached.members);
        try std.testing.expectEqual(@as(usize, 1), cached.miller_cache.?.classes);
        try std.testing.expectEqual(@as(usize, 1), cached.miller_cache.?.borrowed_leaves);
        try std.testing.expectEqual(@as(usize, 0), cached.miller_cache.?.fallbacks);
        const fallback = try Receiver.verifyFixtureSourceWithLimits(a, source.view(), root, sidecar, shapes, false, .{ .miller_cache_bytes = 4096 });
        try std.testing.expectEqual(cached.root_bytes, fallback.root_bytes);
        try std.testing.expectEqual(@as(usize, 0), fallback.miller_cache.?.classes);
        try std.testing.expectEqual(@as(usize, 0), fallback.miller_cache.?.borrowed_leaves);
        try std.testing.expectEqual(@as(usize, 1), fallback.miller_cache.?.fallbacks);
        std.debug.print("OP_MILLER_CACHED_ROOT bytes={} members={} cache={any} fallback={any} native_proof_absent=true proof_unchanged=true security_qualified=false\n", .{ cached.root_bytes, cached.members, cached.miller_cache.?, fallback.miller_cache.? });
    }
    if (budget.snapshot().live_bytes != 0 or budget.snapshot().external_live_bytes != 0) return error.OpRootFixtureLeak;
}
