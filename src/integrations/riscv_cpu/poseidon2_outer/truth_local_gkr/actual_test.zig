//! Pinned real OP capture -> actual sponge-derived truth -> local GKR/P2 -> R6.
//! This proves one actual source family, not a complete execution inventory.
const std = @import("std");
const core = @import("stwo_core");
const engine = @import("stwo_prover_engine");
const Request = @import("../../rv64_ethereum_request.zig");
const Image = @import("../../word16_execution/expected_image.zig");
const Program = @import("../../word16_execution/program.zig").Program;
const Capture = @import("../pure_p2_op_capture.zig");
const Setup = @import("../../word16_global_execution/keccak/shared/roster.zig").TruthSetup;
const R = @import("../../word16_global_execution/services/roster.zig");
const Base = @import("../pure_p2_truth_worker.zig");
const T = @import("worker.zig");
const Manifest = @import("../pure_p2_manifest.zig");
const W = @import("../pure_p2_worker_protocol.zig").W;
const write = @import("../../rv64_ethereum_batch_receipt.zig").writeExclusive;
fn json(a: std.mem.Allocator, dir: std.fs.Dir, name: []const u8, value: anytype) !void {
    const bytes = try std.json.Stringify.valueAlloc(a, value, .{});
    defer a.free(bytes);
    try write(dir, name, bytes);
}
test "OP truth local GKR actual338 sponge Keccak source and R6 gate" {
    const config_path = std.posix.getenv("STWO_OP_TRUTH_LOCAL_GKR_CONFIG") orelse return error.SkipZigTest;
    const out_path = std.posix.getenv("STWO_OP_TRUTH_LOCAL_GKR_OUT") orelse return error.MissingLocalGkrArtifactDirectory;
    const backing = std.testing.allocator;
    const raw = try std.fs.cwd().readFileAlloc(backing, config_path, 16384);
    defer backing.free(raw);
    const parsed = try std.json.parseFromSlice(Request.Config, backing, raw, .{});
    defer parsed.deinit();
    const owner = try engine.host_budget_allocator.SharedHostBudget.create(std.heap.smp_allocator, 16 << 30);
    defer owner.destroy();
    const a = owner.allocator();
    var pool: engine.work_pool.WorkPool = .{};
    try pool.initInPlaceWithOptions(.{ .worker_count = 8 });
    defer pool.deinit();
    var pool_scope = try engine.work_pool.ScopedPoolBinding.init(&pool);
    defer pool_scope.deinit();
    try std.fs.cwd().makeDir(out_path);
    var dir = try std.fs.cwd().openDir(out_path, .{});
    defer dir.close();
    var timer = try std.time.Timer.start();
    var image = try Image.Owner.initForOp(a, parsed.value);
    var owns_image = true;
    defer if (owns_image) image.deinit();
    const image_identity = image.identity;
    var program = try Program.initWithAuthority(a, &image.authority);
    var owns_program = true;
    defer if (owns_program) program.deinit();
    try program.makeCompact();
    var captured = try Capture.Owner.init(a, parsed.value, &image, &program);
    var owns_capture = true;
    defer if (owns_capture) captured.deinit();
    if (captured.steps != 796406 or captured.native.len != 1) return error.WrongActualOpFixture;
    var direct: usize = 0;
    for (captured.advice.keccak) |calls| direct += calls.len;
    var sponge: usize = 0;
    for (captured.advice.sponge) |shard| sponge += shard.inputs.len;
    if (direct != 0 or sponge != 338) return error.WrongActualKeccakCoverage;
    const capture_ns = timer.lap();
    var setup = try Setup.init(a, 13);
    defer setup.deinit();
    const truth = R.Truth{ .keccak = .{ .setup = &setup, .first_id = 1, .calls = 338 } };
    const profile = @import("../op_profile.zig").Profile.op_target_b4_q72_p0_fold4_v1;
    var key = try T.Key.init(a, truth, profile);
    var owns_key = true;
    defer if (owns_key) key.deinit();
    const expected = try key.expected(truth, 0);
    var worker = try T.Worker.init(a, &key, truth, Base.SourceBuilder.fromAdvice(&captured.advice), expected, .{ .live_bytes = 4 << 30, .main_bytes = 256 << 20, .interaction_bytes = 256 << 20, .gkr_bytes = 3 << 30 });
    defer worker.deinit();
    captured.deinit();
    owns_capture = false;
    program.deinit();
    owns_program = false;
    image.deinit();
    owns_image = false;
    const setup_ns = timer.lap();
    var native_recorder = engine.stage_profile.Recorder.initWithOptions(a, "cpu", "actual_op_keccak_truth_local_gkr", .{ .capture_tasks = false, .capture_process_usage = true });
    defer native_recorder.deinit();
    worker.native_recorder = &native_recorder;
    const stage = try worker.seal();
    var entries = [_]Manifest.Entry{.{ .authority = expected, .scope = .{ .statement = expected.statement, .fixed = expected.fixed, .main = stage.main, .ordinal = 0 }, .local = null, .global_relations = expected.global_relations }};
    // Synthetic one-family manifest; complete inventory/global closure is a later
    // gate. Its execution nonce still binds the independently pinned real image.
    const digest = try Manifest.digest(image_identity, &entries);
    const pending = Manifest.Pending{ .entries = &entries, .digest = digest, .shared = try Manifest.drawShared(digest) };
    var encoded = try worker.complete(&pending, 0);
    defer encoded.deinit(a);
    const native_ns = timer.lap();
    const bytes = try T.encode(a, &encoded);
    defer a.free(bytes);
    try write(dir, "native-fragment.bin", bytes);
    try write(dir, "local-gkr.bin", encoded.local);
    var stages = try native_recorder.snapshot(a);
    defer stages.deinit(a);
    try json(a, dir, "native-stages.json", stages);
    try json(a, dir, "native-context.json", .{ .scope = "actual_source_family_only", .complete_execution_accepted = false, .steps = 796406, .direct_keccak_calls = direct, .sponge_permutations = sponge, .source_identity = std.fmt.bytesToHex(image_identity, .lower), .expected = expected, .manifest = digest, .main = stage.main, .local_receipt = encoded.receipt, .claims = encoded.claims, .profile = profile, .capture_ns = capture_ns, .source_setup_ns = setup_ns, .native_ns = native_ns, .worker_peak = worker.budget_owner.snapshot().peak_live_bytes });
    try std.posix.fsync(dir.fd);
    key.deinit();
    owns_key = false;
    var fresh = try T.Key.init(a, truth, profile);
    defer fresh.deinit();
    const fresh_expected = try fresh.expected(truth, 0);
    try std.testing.expectEqualDeep(expected, fresh_expected);
    const retained = try dir.readFileAlloc(a, "native-fragment.bin", 64 << 20);
    defer a.free(retained);
    var decoded = try T.decode(a, retained, 64 << 20);
    defer decoded.deinit(a);
    var capture: core.pcs.ForField(core.fields.om31.OM31).verifier.VerifiedProofCapture(W.H) = undefined;
    _ = try T.verifyWithCapture(a, &fresh, truth, fresh_expected, &pending, 0, &decoded, &capture);
    defer capture.deinit(a);
    const receiver_ns = timer.lap();
    try json(a, dir, "native-receiver.json", .{ .fresh_source_receiver = true, .accepted_fragment = true, .complete_execution_accepted = false, .fresh_receiver_ns = receiver_ns, .native_bytes = encoded.bytes.len, .local_bytes = encoded.local.len, .peak_requested_bytes = owner.snapshot().peak_live_bytes });
    try std.posix.fsync(dir.fd);
    std.debug.print("OP_ACTUAL_TRUTH_LOCAL_GKR native_ns={d} receiver_ns={d} native_bytes={d} local_bytes={d} calls=338 sponge_derived=true\n", .{ native_ns, receiver_ns, encoded.bytes.len, encoded.local.len });
    try @import("r6_leaf_test.zig").Hook.run(a, &fresh, truth, fresh_expected, &pending, &decoded, &capture);
}
