//! M9 canon-leaf: canonical leaf classes (zkDTVM's "shape catalog" analogue).
//!
//! Today a leaf circuit is a function of its segment's exact declaration (rootverify `leafKey` premise; every
//! per-request scalar is already a guessed frame word), so leaf classes almost never recur across blocks: 389
//! distinct classes over the 579 leaves of the 15-block basket [D, receipt catalog-r4.json]. A canonical leaf
//! class is (kind, native family, catalog rung): the segment is padded to the rung's component vector under the
//! strict roster (rv64-m6-native/v2), so the leaf circuit, its PP/FIXED/plan and its authority depend only on
//! the class, and a catalog built once at install covers every block.
//!
//! This file is the host-side PROTOTYPE: class derivation from a declaration, the catalog order/index, and the
//! class key (an ArtifactStore / ClassCache key; it never enters a proof or transcript). Design and soundness:
//! design/riscv-proving-stack/rv64-m9-canon-leaf.md. Selection: STWO_RV64_M9_CANON_LEAF (default off; nothing in
//! the producer or receiver reads it yet - the integration steps are in the design note, section 7).
const std = @import("std");
const Canon = @import("../word16_global_execution/ethereum/canon_native.zig");
const W = @import("../word16_global_execution/services/wire.zig");
const T = @import("../word16_global_execution/services/types.zig");
/// Generated by scripts/rv64_m9_canon_leaf_catalog.py (R = 4 DP rungs per (family, cpu_log) + envelopes).
pub const Catalog = @import("canon_leaf_catalog.zig");

pub const ENV = "STWO_RV64_M9_CANON_LEAF";
pub const Mode = enum {
    /// Default: exact leaf classes (today's bytes and keys).
    off,
    /// Canonical classes: every leaf must map onto the catalog; a miss is an error (no fallback).
    on,
    /// Compute and log the canonical class next to the exact one; proofs unchanged (rollout diagnostic).
    audit,
};
pub fn parseMode(value: ?[]const u8) error{UnknownCanonLeafMode}!Mode {
    const v = value orelse return .off;
    if (v.len == 0 or std.mem.eql(u8, v, "0") or std.mem.eql(u8, v, "off")) return .off;
    if (std.mem.eql(u8, v, "1") or std.mem.eql(u8, v, "on")) return .on;
    if (std.mem.eql(u8, v, "audit")) return .audit;
    return error.UnknownCanonLeafMode;
}
pub fn mode() error{UnknownCanonLeafMode}!Mode {
    return parseMode(std.posix.getenv(ENV));
}

pub const Kind = enum(u32) { cpu = 1, truth = 2 };
/// A canonical leaf class. `rung` indexes the family's catalog list; `index` is the class position in the
/// catalog's canonical order (CPU families ascending, rungs ascending, then truths by (family, aux)) and is the
/// circuit-constant table index of R_leaf[class] (T_nat / T_rec membership at a constant index, canon-vk G01).
pub const LeafClass = struct {
    kind: Kind,
    family: Canon.Family,
    aux: u32 = 0,
    rung: u32,
    index: u32,
};

/// plan.zig PAIRS: (head, tail, reserve) for alu, binary, shift, ls (core LS32) and ls_dword.
const PAIRS = [_][3]u32{ .{ 1, 2, 0 }, .{ 3, 4, 0 }, .{ 5, 6, 0 }, .{ 10, 11, 1 }, .{ 38, 39, 1 } };
fn paired(c: usize) bool {
    for (PAIRS) |p| if (c == p[0] or c == p[1]) return true;
    return false;
}
fn capacity(head: u32, tail: u32, reserve: u32) u64 {
    if (head == 0) return 0;
    var cap: u64 = (@as(u64, 1) << @intCast(head)) - reserve;
    if (tail != 0) cap += (@as(u64, 1) << @intCast(tail)) - reserve;
    return cap;
}

/// The strict-roster fit of plan.zig `canonFitStrict`, evaluated on a declaration alone: the head/tail pair
/// counts are bounded by the declaration's own capacity (an upper bound on the real count), so this never
/// accepts a rung the production fit (which sees the counts) would reject; it may pick a larger rung [D].
/// cpu_log and boundary_log must be equal (capture fixes cpu_log; boundary is a roster constant); an omitted
/// empty division needs the rung to commit division; every other present component must fit under the rung.
pub fn strictFit(d: W.CpuDeclaration, rung: Canon.CpuVector, dword_layout: bool) bool {
    const actual = Canon.cpuVector(d);
    for (actual, rung, 0..) |a, r, c| {
        if (paired(c)) continue;
        if (c == 0 or c == 12) {
            if (r != a) return false;
            continue;
        }
        if (c == 8 and d.geometry.omit_empty_division) {
            if (r == 0) return false;
            continue;
        }
        if (a != 0 and (r == 0 or r < a)) return false;
    }
    for (PAIRS) |p| {
        const h = p[0];
        const t = p[1];
        if (rung[h] == 0) {
            if (actual[h] != 0) return false;
            continue;
        }
        if (h == 38 and !dword_layout) return false;
        if (capacity(actual[h], actual[t], p[2]) > capacity(rung[h], rung[t], p[2])) return false;
    }
    return true;
}

/// Catalog position of a class (canonical order, see LeafClass.index).
pub fn indexOf(table: anytype, family: Canon.Family, aux: u32, rung: u32) ?u32 {
    var i: u32 = 0;
    for (table.CPU) |e| {
        if (e.family == family and aux == 0) return if (rung < e.rungs.len) i + rung else null;
        i += @intCast(e.rungs.len);
    }
    for (table.TRUTH) |e| {
        if (e.family == family and e.aux == aux) return if (rung < e.logs.len) i + rung else null;
        i += @intCast(e.logs.len);
    }
    return null;
}
pub fn count(table: anytype) u32 {
    var n: u32 = 0;
    for (table.CPU) |e| n += @intCast(e.rungs.len);
    for (table.TRUTH) |e| n += @intCast(e.logs.len);
    return n;
}

/// Class of CPU segment `ordinal` of `segments`: the first rung of its family (list order = (cpu_log, cells))
/// that strictly fits. error.CanonLeafNoClass = the catalog does not cover it (miss path, design sec. 3.3).
pub fn cpuClass(table: anytype, d: W.CpuDeclaration, ordinal: usize, segments: usize, dword_layout: bool) error{ CanonLeafNoClass, CanonLeafFamilyMissing }!LeafClass {
    const family = Canon.Family.cpu(ordinal, segments);
    for (table.CPU) |e| if (e.family == family) {
        for (e.rungs, 0..) |rung, r| if (strictFit(d, rung, dword_layout)) {
            return .{ .kind = .cpu, .family = family, .rung = @intCast(r), .index = indexOf(table, family, 0, @intCast(r)).? };
        };
        return error.CanonLeafNoClass;
    };
    return error.CanonLeafFamilyMissing;
}
/// Class of a truth leaf: the smallest rung of (family, profile word logs[1]) holding logs[0]
/// (plan.zig canonicalTruths). Call spans and first ids are statement words, never class inputs.
pub fn truthClass(table: anytype, family: T.Family, logs: [2]u32) error{ CanonLeafNoClass, CanonLeafFamilyMissing }!LeafClass {
    const f = Canon.Family.truth(family);
    for (table.TRUTH) |e| if (e.family == f and e.aux == logs[1]) {
        for (e.logs, 0..) |l, r| if (l >= logs[0]) {
            return .{ .kind = .truth, .family = f, .aux = logs[1], .rung = @intCast(r), .index = indexOf(table, f, logs[1], @intCast(r)).? };
        };
        return error.CanonLeafNoClass;
    };
    return error.CanonLeafFamilyMissing;
}

/// v2 layout flags word of every canonical CPU class: omit_empty_division is always false under the strict roster
/// (division committed at its rung log); fused tail, u8 pairs and compact decode are the production layout.
pub const CPU_LAYOUT_FLAGS: u32 = (1 << 1) | (1 << 2) | (1 << 3);

/// S^nat of a catalog class (canon-native structure v2: the rung vector + layout flags; truth: (main, aux)).
pub fn structure(table: anytype, class: LeafClass) Canon.Digest {
    switch (class.kind) {
        .cpu => for (table.CPU) |e| if (e.family == class.family) return Canon.cpuStructureV2(class.family, class.rung, e.rungs[class.rung], CPU_LAYOUT_FLAGS),
        .truth => for (table.TRUTH) |e| if (e.family == class.family and e.aux == class.aux) {
            return Canon.structureDigestV2(@intFromEnum(class.family), class.rung, &.{ 0, 1 }, &.{ e.logs[class.rung], e.aux }, 0);
        },
    }
    unreachable;
}
/// rung_table_id of the catalog (canon-native section 1 rule over structure v2): binds every class of the
/// catalog, so a leaf key from another catalog never collides.
pub fn rungTableId(table: anytype) Canon.Digest {
    var h = Canon.Hasher.init(.structure_v2);
    h.words(&.{ 0xFFFFFFFF, @intCast(table.CPU.len + table.TRUTH.len) });
    for (table.CPU) |e| {
        h.words(&.{ @intFromEnum(e.family), @intCast(e.rungs.len) });
        for (e.rungs, 0..) |v, r| h.digest(Canon.cpuStructureV2(e.family, @intCast(r), v, CPU_LAYOUT_FLAGS));
    }
    for (table.TRUTH) |e| {
        h.words(&.{ @intFromEnum(e.family), e.aux, @intCast(e.logs.len) });
        for (e.logs, 0..) |l, r| h.digest(Canon.structureDigestV2(@intFromEnum(e.family), @intCast(r), &.{ 0, 1 }, &.{ l, e.aux }, 0));
    }
    return h.final();
}

pub const LEAF_TAG = "rv64-m9-canon-leaf-class/v1";
/// Everything a canonical leaf circuit is a function of. Exactly these, and no per-segment value: the
/// statement (ordinal, epoch, steps, pcs/registers/clocks, rows/calls/first ids, manifest, claims, chi) is
/// guessed frame words today and stays so (design sec. 2).
pub const KeyInputs = struct {
    class: LeafClass,
    rung_table_id: Canon.Digest,
    /// Native profile identity (W.Candidate.profileIdentity, e.g. d2_native_b4_q54_p20_fold4).
    native_profile: Canon.Digest,
    /// Program identity (ELF + ROM authority): the guest, not the block.
    image: Canon.Digest,
    /// Native PCS config identity (cpu_statement.configIdentity).
    pcs_config: Canon.Digest,
    /// Outer protocol domain (om31 protocol domainName(), hashed) and the outer shape rule (exact 0, uniform-v1 1,
    /// set-v2 2): the leaf's own padding target is a function of the class under every rule but exact.
    outer_domain: Canon.Digest,
    outer_shape: u32,
};
/// Native class key (canon-native ClassKey) of the leaf's native class.
pub fn nativeClassKey(k: KeyInputs) Canon.Digest {
    return (Canon.ClassKey{ .family = @intFromEnum(k.class.family), .rung = k.class.rung, .profile_identity = k.native_profile, .image = k.image, .rung_table_id = k.rung_table_id }).digest();
}
/// Canonical leaf class key: H(tag, [kind, family, aux, rung, index] || native_class_key || pcs || domain || shape)
/// under canon-native's word rule (Blake2s(Blake2s(tag) || LE32 words)). Host-only (store/ClassCache key).
pub fn classKey(k: KeyInputs) Canon.Digest {
    var tag: [32]u8 = undefined;
    std.crypto.hash.blake2.Blake2s256.hash(LEAF_TAG, &tag, .{});
    var h = Canon.Hasher{ .h = std.crypto.hash.blake2.Blake2s256.init(.{}) };
    h.digest(tag);
    h.words(&.{ @intFromEnum(k.class.kind), @intFromEnum(k.class.family), k.class.aux, k.class.rung, k.class.index });
    h.digest(nativeClassKey(k));
    h.digest(k.pcs_config);
    h.digest(k.outer_domain);
    h.word(k.outer_shape);
    return h.final();
}
