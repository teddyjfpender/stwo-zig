//! Fully propagated noncanonical state: all local CPU/REG/OWNER obligations
//! close; the accepting receiver must still authenticate its RAM ancestry.
const std = @import("std");
const core = @import("stwo_core");
const engine = @import("stwo_prover_engine");
const Backend = @import("stwo_cpu_backend").CpuBackend;
const wire = @import("stwo_proof_wire");
const front = @import("stwo_riscv_frontend");
const A = front.rv64_air;
const LS = A.memory.load_store_v2;
const P = @import("../protocol.zig");
const Mat = @import("../setup.zig");
const Sources = @import("../sources.zig");
const Components = @import("../components.zig").Components;
const Execution = @import("../execution.zig");
const H = @import("joint_write_attack_support.zig");
const M = H.M;
const Q = H.Q;
const a = std.testing.allocator;
fn sumClaims(c: P.Claims) Q {
    var out = Q.zero();
    for (c.values()) |v| out = out.add(v);
    return out;
}
test "LS32 actual balanced LD REG SD chain has only unanchored RAM ancestry and fails fresh closed verification" {
    var setup = try Mat.Setup.init(a, .{ .base = 4096, .words = &H.WORDS }, .{ .cpu_log = 5 });
    defer setup.deinit();
    var tape = try H.tape(a, 0, 6);
    defer tape.deinit();
    const public = H.boundary(0, 6);
    const admission = Execution.Admission{ .image = H.image(), .image_identity = @splat(0x91), .initial_pc = public.initial_pc, .initial_registers = public.initial_registers };
    var source = try Sources.Source.init(a, &setup.materials, H.image(), public, 1, &tape);
    defer source.deinit();
    const request = source.request();
    try admission.validate(&setup, request);
    const honest_cpu = try a.dupe(M, source.cpu.main);
    defer a.free(honest_cpu);
    const honest_ls = try a.dupe(M, source.memory.ls.main);
    defer a.free(honest_ls);
    H.forge(source.cpu.main, source.memory.ls.main, 0, 6);
    const forged_cpu = try a.dupe(M, source.cpu.main);
    defer a.free(forged_cpu);
    const forged_ls = try a.dupe(M, source.memory.ls.main);
    defer a.free(forged_ls);
    var scheme = try P.T.Scheme.init(a, P.T.P.config());
    var owns = true;
    defer if (owns) scheme.deinit(a);
    scheme.setCompactPolynomialStorage(5);
    var channel = P.T.P.Channel{};
    try P.mix(&channel, &setup, request, admission.image_identity);
    try setup.appendFixed(a, &scheme, &channel);
    const main = try source.columns(a, 1);
    defer a.free(main);
    try scheme.commitBorrowedStreaming(a, main, 8, &channel);
    try source.releaseMain();
    const draw = P.draw(&channel);
    var claims = (try source.generateForDelegationJoin(draw)).physical;
    const cpu_scratch = try a.alloc(M, A.word16_execution.layout.inter.COUNT * H.N);
    defer a.free(cpu_scratch);
    const ls_scratch = try a.alloc(M, LS.layout.INTERACTION * H.N);
    defer a.free(ls_scratch);
    const honest_ca = try H.repairCpu(honest_cpu, cpu_scratch, public, 1, draw.cpu);
    const honest_lc = try H.repairLs(honest_ls, ls_scratch, draw.memory);
    const ca = try H.repairCpu(forged_cpu, source.cpu.interaction, public, 1, draw.cpu);
    const lc = try H.repairLs(forged_ls, source.memory.ls.interaction, draw.memory);
    try std.testing.expect(honest_ca.register.eql(ca.register));
    try std.testing.expect(ca.register.add(claims.regboundary).isZero());
    try std.testing.expect(honest_ca.function.eql(ca.function));
    try std.testing.expect(ca.owner.add(lc.owner).isZero());
    try std.testing.expect(honest_lc.range16.eql(lc.range16));
    try std.testing.expect(honest_lc.range8.eql(lc.range8));
    try std.testing.expect(honest_lc.selection.eql(lc.selection));
    claims.cpu = ca.total;
    claims.ls = lc;
    try std.testing.expect(sumClaims(claims).sub(P.ramClaim(claims)).isZero());
    try std.testing.expect(!P.ramClaim(claims).isZero());
    try std.testing.expectError(error.UnclosedExecutionRelations, claims.validate());
    channel.mixFelts(&claims.values());
    const inter = try source.columns(a, 2);
    defer a.free(inter);
    try scheme.commitBorrowedStreaming(a, inter, 8, &channel);
    source.releaseCommittedInteraction();
    var components = try Components.init(&setup.materials, request, draw, claims);
    const handles = try components.provers(a);
    defer a.free(handles);
    owns = false;
    var proof = try engine.prove.proveExWithRecorder(Backend, P.T.P.Hasher, P.T.P.MerkleChannel, a, handles, &channel, scheme, false, null);
    defer proof.aux.deinit(a);
    defer proof.proof.deinit(a);
    const bytes = try wire.encodeProofBytesBinary(a, proof.proof);
    defer a.free(bytes);
    var fresh = try Mat.Setup.init(a, .{ .base = 4096, .words = &H.WORDS }, setup.materials.geometry);
    defer fresh.deinit();
    const encoded = Execution.Encoded{ .bytes = bytes, .claims = claims, .request = request };
    try @import("boundary_anchor_test.zig").verifyPhysical(&fresh, admission, encoded);
    try std.testing.expectError(error.UnclosedExecutionRelations, Execution.verify(a, &fresh, admission, encoded));
}
